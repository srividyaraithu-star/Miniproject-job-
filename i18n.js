function translateDynamicValue(value, lang) {
    if (lang === "en" || !value) {
        return value;
    }

    const dictionary = dynamicTranslations[lang];
    if (!dictionary) {
        return value;
    }

    const normalized = value.trim().toLowerCase();
    if (dictionary.phrases[normalized]) {
        return dictionary.phrases[normalized];
    }

    return value.replace(/[A-Za-z0-9]+/g, word => {
        const key = word.trim().toLowerCase();
        return dictionary.words[key] || transliterateWord(word, lang);
    });
}

